-- Oracle 19c: D01 development schema. Review names against company schema before applying.
-- No DROP statements; run once in a dedicated development schema. No production data.
CREATE SEQUENCE CARGO_D_REQUEST_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE CARGO_D_LOG_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE CARGO_D_REQUEST (
    REQUEST_ID NUMBER(18) NOT NULL,
    REQUEST_NO VARCHAR2(32 CHAR),
    OWNER_ID NVARCHAR2(200),
    STATUS VARCHAR2(20 CHAR),
    VERSION_NO NUMBER(10),
    CREATED_AT DATE,
    UPDATED_AT DATE,
    REVIEW_NOTE NVARCHAR2(1000),
    APPROVER_NAME NVARCHAR2(100),
    DISPATCHED_AT DATE,
    DISPATCHED_BY NVARCHAR2(100),
    DISPATCH_NOTE NVARCHAR2(1000),
    OUTCOME VARCHAR2(20 CHAR),
    SIGN_STATUS VARCHAR2(20 CHAR),
    DISPATCH_NO VARCHAR2(32 CHAR),
    VEHICLE NVARCHAR2(100),
    DRIVER1 NVARCHAR2(100),
    DRIVER2 NVARCHAR2(100),
    USAGE_AT DATE,
    PENDING_RETURN_AT DATE,
    RETURN_REQUESTED_AT DATE,
    RETURN_REASON NVARCHAR2(1000),
    CATEGORY VARCHAR2(20 CHAR),
    TRANSPORT_TYPE NVARCHAR2(20),
    APPLICANT NVARCHAR2(100),
    DEPT NVARCHAR2(100),
    EXT NVARCHAR2(30),
    PLAN_CODE NVARCHAR2(100),
    CAMPUS NVARCHAR2(50),
    PREFERENCE1 NVARCHAR2(50),
    PREFERENCE2 NVARCHAR2(50),
    PREFERENCE3 NVARCHAR2(50),
    EXERCISE_PLAN NVARCHAR2(200),
    LEADER NVARCHAR2(100),
    LEADER_EXT NVARCHAR2(30),
    LEADER_PHONE NVARCHAR2(30),
    PICKUP_LOCATION NVARCHAR2(300),
    PURPOSE NVARCHAR2(1000),
    TRIPLICATE_NO NVARCHAR2(100),
    ESCORT_NO NVARCHAR2(100),
    CHANGE_REASON NVARCHAR2(1000),
    REMARKS NVARCHAR2(1000),
    START_AT DATE,
    END_AT DATE,
    PAX NUMBER(6),
    SELF_DRIVE NUMBER(1),
    NEED_K NUMBER(1),
    NEED_P NUMBER(1),
    ONE_WAY NUMBER(1),
    ALLOW_MERGE NUMBER(1),
    NIGHT_OT NUMBER(1),
    HOLIDAY_OT NUMBER(1),
    CONTINUE_MATCHING NUMBER(1),
    WILLING_SELF_DRIVE NUMBER(1),
    QUALIFIED_LICENSE NUMBER(1),
    ENTER_TAIPEI NUMBER(1),
    CROSS_CAMPUS NUMBER(1),
    HAS_CARGO NUMBER(1),
    HAZARDOUS_CARGO NUMBER(1),
    PYROTECHNIC_CARGO NUMBER(1),
    NEEDS_HOISTING NUMBER(1),
    REQUEST_REVIEW NUMBER(1),
    CONSTRAINT CARGO_D_REQUEST_PK PRIMARY KEY (REQUEST_ID),
    CONSTRAINT CARGO_D_REQUEST_NO_UK UNIQUE (REQUEST_NO),
    CONSTRAINT CARGO_D_PERIOD_CK CHECK (END_AT > START_AT),
    CONSTRAINT CARGO_D_PAX_CK CHECK (PAX >= 1),
    CONSTRAINT CARGO_D_STATUS_CK CHECK (STATUS IN ('draft','submitted','rejected','approved','noVehicle','dispatched'))
);

CREATE TABLE CARGO_D_LOCATION (
    REQUEST_ID NUMBER(18) NOT NULL,
    LINE_NO NUMBER(6) NOT NULL,
    NAME NVARCHAR2(300),
    CONSTRAINT CARGO_D_LOCATION_PK PRIMARY KEY (REQUEST_ID, LINE_NO),
    CONSTRAINT CARGO_D_LOCATION_FK FOREIGN KEY (REQUEST_ID) REFERENCES CARGO_D_REQUEST(REQUEST_ID)
);

CREATE TABLE CARGO_D_SELF_DRIVER (
    REQUEST_ID NUMBER(18) NOT NULL,
    LINE_NO NUMBER(6) NOT NULL,
    NAME NVARCHAR2(100),
    EXT NVARCHAR2(30),
    PHONE NVARCHAR2(30),
    CONSTRAINT CARGO_D_SELF_DRIVER_PK PRIMARY KEY (REQUEST_ID, LINE_NO),
    CONSTRAINT CARGO_D_SELF_DRIVER_FK FOREIGN KEY (REQUEST_ID) REFERENCES CARGO_D_REQUEST(REQUEST_ID)
);

CREATE TABLE CARGO_D_CARGO (
    REQUEST_ID NUMBER(18) NOT NULL,
    LINE_NO NUMBER(6) NOT NULL,
    NAME NVARCHAR2(200),
    LENGTH_CM NUMBER(12,3),
    WIDTH_CM NUMBER(12,3),
    HEIGHT_CM NUMBER(12,3),
    WEIGHT_KG NUMBER(12,3),
    QUANTITY NUMBER(9),
    CATEGORY VARCHAR2(50 CHAR),
    PACKAGING NVARCHAR2(200),
    HAZARDOUS NUMBER(1),
    CONSTRAINT CARGO_D_CARGO_PK PRIMARY KEY (REQUEST_ID, LINE_NO),
    CONSTRAINT CARGO_D_CARGO_FK FOREIGN KEY (REQUEST_ID) REFERENCES CARGO_D_REQUEST(REQUEST_ID)
);

CREATE TABLE CARGO_D_LOG (
    LOG_ID NUMBER(18) NOT NULL,
    REQUEST_ID NUMBER(18) NOT NULL,
    ACTION NVARCHAR2(100),
    ACTOR NVARCHAR2(200),
    NOTE NVARCHAR2(2000),
    CREATED_AT DATE,
    CONSTRAINT CARGO_D_LOG_PK PRIMARY KEY (LOG_ID),
    CONSTRAINT CARGO_D_LOG_FK FOREIGN KEY (REQUEST_ID) REFERENCES CARGO_D_REQUEST(REQUEST_ID)
);

CREATE TABLE CARGO_D_ASSIGNMENT (
    REQUEST_ID NUMBER(18) NOT NULL,
    LINE_NO NUMBER(6) NOT NULL,
    FROM_AT DATE,
    TO_AT DATE,
    VEHICLE NVARCHAR2(100),
    DRIVER1 NVARCHAR2(100),
    DRIVER2 NVARCHAR2(100),
    KIND NVARCHAR2(50),
    REASON NVARCHAR2(1000),
    ACTOR NVARCHAR2(200),
    CONSTRAINT CARGO_D_ASSIGNMENT_PK PRIMARY KEY (REQUEST_ID, LINE_NO),
    CONSTRAINT CARGO_D_ASSIGNMENT_FK FOREIGN KEY (REQUEST_ID) REFERENCES CARGO_D_REQUEST(REQUEST_ID)
);

CREATE TABLE CARGO_D_NOTICE (
    REQUEST_ID NUMBER(18) NOT NULL,
    LINE_NO NUMBER(6) NOT NULL,
    SENT_AT DATE,
    RECIPIENT NVARCHAR2(200),
    KIND NVARCHAR2(100),
    MESSAGE NVARCHAR2(1000),
    CONSTRAINT CARGO_D_NOTICE_PK PRIMARY KEY (REQUEST_ID, LINE_NO),
    CONSTRAINT CARGO_D_NOTICE_FK FOREIGN KEY (REQUEST_ID) REFERENCES CARGO_D_REQUEST(REQUEST_ID)
);

CREATE TABLE CARGO_D_OPTION (
    OPTION_TYPE VARCHAR2(30 CHAR) NOT NULL,
    CODE NVARCHAR2(50) NOT NULL,
    LABEL NVARCHAR2(100),
    SORT_NO NUMBER(6),
    ACTIVE NUMBER(1),
    CONSTRAINT CARGO_D_OPTION_PK PRIMARY KEY (OPTION_TYPE, CODE)
);

CREATE INDEX CARGO_D_OWNER_DATE_IX ON CARGO_D_REQUEST(OWNER_ID, CREATED_AT);
CREATE INDEX CARGO_D_LOG_REQ_IX ON CARGO_D_LOG(REQUEST_ID, LOG_ID);
