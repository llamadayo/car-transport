-- D02-D04 draft schema; review before running against Oracle 19c.

-- C module/maintenance/leave integration supplies resource blocks.

CREATE TABLE CARGO_D_APPROVER (
    OWNER_ID NVARCHAR2(200) NOT NULL,
    APPROVER_ID NVARCHAR2(200) NOT NULL,
    ACTIVE NUMBER(1) NOT NULL,
    CONSTRAINT CARGO_D_APPROVER_PK PRIMARY KEY (OWNER_ID, APPROVER_ID)
);

CREATE TABLE CARGO_D_RESOURCE (
    RESOURCE_ID NVARCHAR2(100) NOT NULL,
    KIND VARCHAR2(10) NOT NULL,
    NAME NVARCHAR2(100),
    POOL VARCHAR2(10),
    SITE NVARCHAR2(50),
    VEHICLE_TYPE NVARCHAR2(50),
    SEATS NUMBER(6),
    TONS NUMBER(9,3),
    PERMIT_K NUMBER(1),
    PERMIT_P NUMBER(1),
    ACTIVE NUMBER(1),
    CONSTRAINT CARGO_D_RESOURCE_PK PRIMARY KEY (RESOURCE_ID)
);

CREATE TABLE CARGO_D_RESOURCE_BLOCK (
    BLOCK_ID NUMBER(18) NOT NULL,
    RESOURCE_ID NVARCHAR2(100) NOT NULL,
    FROM_AT DATE NOT NULL,
    TO_AT DATE NOT NULL,
    SOURCE VARCHAR2(30),
    REASON NVARCHAR2(500),
    CONSTRAINT CARGO_D_RESOURCE_BLOCK_PK PRIMARY KEY (BLOCK_ID)
);

CREATE TABLE CARGO_D_SIGN (
    REQUEST_ID NUMBER(18) NOT NULL,
    ROUND_NO NUMBER(6) NOT NULL,
    STATUS VARCHAR2(20),
    SUBMITTED_BY NVARCHAR2(200),
    SUBMITTED_AT DATE,
    SUMMARY NVARCHAR2(1000),
    DECIDED_BY NVARCHAR2(200),
    DECIDED_AT DATE,
    NOTE NVARCHAR2(1000),
    CONSTRAINT CARGO_D_SIGN_PK PRIMARY KEY (REQUEST_ID, ROUND_NO)
);

ALTER TABLE CARGO_D_RESOURCE_BLOCK ADD CONSTRAINT CARGO_D_BLOCK_PERIOD_CK CHECK (TO_AT > FROM_AT);

ALTER TABLE CARGO_D_RESOURCE_BLOCK ADD CONSTRAINT CARGO_D_BLOCK_RESOURCE_FK FOREIGN KEY (RESOURCE_ID) REFERENCES CARGO_D_RESOURCE(RESOURCE_ID);

ALTER TABLE CARGO_D_SIGN ADD CONSTRAINT CARGO_D_SIGN_REQ_FK FOREIGN KEY (REQUEST_ID) REFERENCES CARGO_D_REQUEST(REQUEST_ID);

CREATE INDEX CARGO_D_BLOCK_PERIOD_IX ON CARGO_D_RESOURCE_BLOCK(RESOURCE_ID, FROM_AT, TO_AT);

COMMIT;