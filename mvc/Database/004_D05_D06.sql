-- D05 usage revisions are append-only; D06 account mapping is a draft integration contract.
CREATE TABLE CARGO_D_USAGE (
    REQUEST_ID NUMBER(18) NOT NULL,
    REVISION_NO NUMBER(6) NOT NULL,
    VEHICLE_TYPE NVARCHAR2(50) NOT NULL,
    VEHICLE NVARCHAR2(100) NOT NULL,
    DRIVER1 NVARCHAR2(100) NOT NULL,
    DRIVER2 NVARCHAR2(100),
    START_KM NUMBER(12,3) NOT NULL,
    END_KM NUMBER(12,3) NOT NULL,
    DISTANCE_KM NUMBER(12,1) NOT NULL,
    RECORDED_BY NVARCHAR2(200) NOT NULL,
    RECORDED_AT DATE NOT NULL,
    CONSTRAINT CARGO_D_USAGE_PK PRIMARY KEY (REQUEST_ID, REVISION_NO),
    CONSTRAINT CARGO_D_USAGE_FK FOREIGN KEY (REQUEST_ID) REFERENCES CARGO_D_REQUEST(REQUEST_ID),
    CONSTRAINT CARGO_D_USAGE_KM_CK CHECK (START_KM >= 0 AND END_KM >= START_KM)
);

CREATE TABLE CARGO_D_DRIVER_USER (
    USER_ID NVARCHAR2(200) NOT NULL,
    RESOURCE_ID NVARCHAR2(100) NOT NULL,
    ACTIVE NUMBER(1) NOT NULL,
    CONSTRAINT CARGO_D_DRIVER_USER_PK PRIMARY KEY (USER_ID, RESOURCE_ID),
    CONSTRAINT CARGO_D_DRIVER_USER_FK FOREIGN KEY (RESOURCE_ID) REFERENCES CARGO_D_RESOURCE(RESOURCE_ID)
);
